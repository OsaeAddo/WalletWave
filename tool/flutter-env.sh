#!/usr/bin/env bash
# Builds .env.flutter from .env.local, keeping only the values that are safe to
# compile into the desktop app.
#
# Why a separate file: `--dart-define-from-file=.env.local` would pass the
# database password, S3 secret and realtime secret to the compiler. Anyone can
# extract strings from a Linux binary, so those must never be handed to
# Flutter. This script copies the three public URLs and nothing else.
set -euo pipefail

cd "$(dirname "$0")/.."

src=.env.local
if [[ ! -f "$src" ]]; then
  echo "missing $src; run 'npx neon deploy' first" >&2
  exit 1
fi

read_value() {
  grep -E "^$1=" "$src" | head -1 | cut -d= -f2-
}

auth_url="$(read_value NEON_AUTH_BASE_URL)"
data_url="$(read_value NEON_DATA_API_URL)"
branch_id="$(read_value NEON_BRANCH_ID)"
host_suffix="$(read_value NEON_FUNCTION_HOST_SUFFIX)"

if [[ -z "$auth_url" || -z "$data_url" || -z "$branch_id" || -z "$host_suffix" ]]; then
  echo "one of the Neon URLs is missing from $src; run 'npx neon deploy'" >&2
  exit 1
fi

functions_url="https://${branch_id}-api${host_suffix}/"

umask 077
cat > .env.flutter <<EOF
# Generated by tool/flutter-env.sh. Public URLs only; do not commit.
NEON_AUTH_BASE_URL=$auth_url
NEON_DATA_API_URL=$data_url
NEON_FUNCTIONS_BASE_URL=$functions_url
EOF

echo "wrote .env.flutter with 3 public values"
